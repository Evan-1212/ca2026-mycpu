package mycpu.common

import java.nio.charset.StandardCharsets
import java.nio.file.{Files, Paths}

import circt.stage.ChiselStage

/** Emits the Verilator model of a task (INF-04 step 1): `<dir>/SimTop.sv`, one file with the whole
  * design (module `SimTop`, see `SimTop.desiredName`), and `<dir>/sim_config.h`, the elaboration
  * parameters that the C++ harness (`sim/main.cpp`) needs: the RAM base and size, the UART divider,
  * the git commit the model was elaborated from, and the fields of an `+obs-trace` record
  * (`SIM_OBS_FIELDS`, from [[ObsFields.of]], which `sim/obs.cpp` reads).
  *
  * Verification layers (INF-04 step 1a), as checked with Chisel 7.16.0 and firtool 1.160.0: Chisel
  * places `assert`, `assume`, `cover` and `printf` in the `Verification` layers. By default
  * firtool extracts each layer into a module of its own under `verification/`, instantiated by a
  * `bind` statement in a separate `layers-<top>-Verification*.sv` file, and leaves those files out
  * of `filelist.f`: a model built from the main file alone has no assertion and no `printf`, so a
  * checker passes vacuously. (`emitSystemVerilog`, which returns one string, keeps the layer files
  * in it, and their `include "layers-..."` lines then fail to resolve in Verilator.)
  * `-default-layer-specialization=enable` enables every layer at
  * compile time instead: firtool inlines their contents into the modules and emits no layer or
  * bind file (`-enable-layers=Verification,...` does the same but must name every layer; the
  * bootcamp's `Yosys.verilog` uses `=disable` to drop them). A Chisel `assert` becomes an
  * `if (cond) begin $error(...); $fatal; end` in an `always` block under `ifndef SYNTHESIS`, an
  * immediate check that Verilator runs with or without `--assert`; the harness still builds with
  * `--assert` so SystemVerilog assertions in hand-written or future code fire too. The harness
  * turns the `$fatal` into exit code 3.
  */
object TopGen {

  val firtoolOptions: Array[String] = Array(
    "-disable-all-randomization", // no random initial values (they overwrote a loaded program in ca2025)
    "-strip-debug-info",
    "-default-layer-specialization=enable" // assertions and printf inline, see above
  )

  /** Elaborates `gen` and writes `SimTop.sv` and `sim_config.h` into `dir`. */
  def emit(gen: => SimTop, dir: String): Unit = {
    var top: Option[SimTop] = None
    // emitSystemVerilog returns the whole design as one string (emitSystemVerilogFile with a target
    // directory splits it into a file per module), so the model has one source file.
    val verilog = ChiselStage.emitSystemVerilog({ val t = gen; top = Some(t); t }, Array.empty, firtoolOptions)
    val t       = top.get
    require(t.uartDivider >= 1, "the UART divider must be at least 1")
    require(t.ramBytes > 0 && t.ramBytes % 4 == 0, "the RAM size must be a positive number of words")
    Files.createDirectories(Paths.get(dir))
    Files.write(Paths.get(dir, "SimTop.sv"), verilog.getBytes(StandardCharsets.UTF_8))
    val fields = ObsFields.of(t).map(f => s"""    X(${f.port}, "${f.name}", ${f.bits})""")
    val header =
      s"""|// Generated by mycpu.common.TopGen for ${t.getClass.getName}; do not edit.
          |#pragma once
          |#define SIM_TOP_CLASS "${t.getClass.getName}"
          |#define SIM_RAM_BASE 0x${t.ramBase.toHexString}u
          |#define SIM_RAM_BYTES ${t.ramBytes}u
          |#define SIM_UART_DIVIDER ${t.uartDivider}u
          |#define SIM_SIMCTRL_EXIT 0x${(MemMap.simCtrlBase + MemMap.SimCtrl.Exit).toHexString}u
          |#define SIM_EXIT_LEAD ${CoSimRules().exitLead}u
          |#define SIM_GIT_COMMIT "$commit"
          |#define SIM_OBS_GROUPS "${t.obsGroups.names.mkString(",")}"
          |// X(<port without io_>, "<schema field>", <bits>): the fields of an +obs-trace record
          |#define SIM_OBS_FIELDS(X) \\
          |${fields.mkString(" \\\n")}
          |""".stripMargin
    Files.write(Paths.get(dir, "sim_config.h"), header.getBytes(StandardCharsets.UTF_8))
  }

  /** The commit that `HEAD` names, with `-dirty` if a tracked file differs from it, or `unknown`
    * outside a git checkout: the observation header's `commit` (OBS-01). It is taken when the
    * model is elaborated.
    */
  def commit: String = {
    import scala.sys.process._
    val quiet = ProcessLogger(_ => ())
    try {
      val head  = Seq("git", "rev-parse", "HEAD").!!(quiet).trim
      val dirty = Seq("git", "status", "--porcelain", "--untracked-files=no").!!(quiet).trim.nonEmpty
      if (head.matches("[0-9a-f]{40}")) head + (if (dirty) "-dirty" else "") else "unknown"
    } catch { case _: Exception => "unknown" }
  }

  /** `sbt "<project>/runMain mycpu.common.TopGen <class> <dir>"`: emits the top of class `<class>`
    * (a `SimTop` with a constructor without arguments) into `<dir>`. Use `Test/runMain` for a top
    * defined in test sources.
    */
  def main(args: Array[String]): Unit = {
    if (args.length != 2) {
      System.err.println("usage: TopGen <SimTop class> <output dir>")
      sys.exit(2)
    }
    def fail(reason: String): Nothing = {
      System.err.println(s"TopGen: ${args(0)} $reason")
      sys.exit(2)
    }
    val cls =
      try Class.forName(args(0))
      catch { case _: ClassNotFoundException => fail("is not a class on the class path") }
    if (!classOf[SimTop].isAssignableFrom(cls)) fail("is not a mycpu.common.SimTop")
    if (java.lang.reflect.Modifier.isAbstract(cls.getModifiers)) fail("is abstract")
    val constructor =
      try cls.getConstructor()
      catch {
        case _: NoSuchMethodException =>
          fail("has no public constructor without arguments (a Scala object or an inner class cannot be a top)")
      }
    // newInstance wraps whatever the module's body throws; Chisel reports the cause itself
    emit(
      try constructor.newInstance().asInstanceOf[SimTop]
      catch { case e: java.lang.reflect.InvocationTargetException => throw e.getCause },
      args(1)
    )
  }
}
