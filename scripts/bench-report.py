"""BEN-03: the benchmark report of every task, from the files `make bench` writes in each task.

    bench-report.py --bench BUILD/bench --out BUILD/bench/report [--tasks T1,T2,...]

It reads BUILD/bench/t<n>.csv (scripts/bench-run.sh, one row per variant, build and workload) for
every task and writes
  - <out>.csv: one row per (task, variant, arch, benchmark), the columns of bench-run.sh, the hpm
    columns empty before T3, rows in task order and then in the order of each task's file;
  - <out>.md: the same rows as one Markdown table per task, with cycles, instret, CPI, the score
    and, from T3 on, the partition events.
Both depend on the CSV files only, so two runs of `make bench` give identical reports (the
simulation is cycle-exact). It fails when a task's file is missing, has a malformed row or a
(variant, arch, benchmark) twice, or has a number of rows other than its benchmark set gives: for
each (variant, arch) a dhrystone, a duremark and eight qrcode-<table|bitwise>-<L|M|Q|H> rows.
"""

import argparse
import csv
import io
import os
import sys

TASKS = ("T1", "T2", "T3", "T4", "T5")
BASE = ["task", "variant", "arch", "benchmark", "cycles", "instret", "cpi", "score", "score_unit",
        "run_cycles", "run_instret", "run_cpi", "exit"]
HPM = ["hpm_cycles", "hpm_instret"] + [f"hpm{i}" for i in range(1, 9)]
WORKLOADS = ["dhrystone", "duremark"] + [f"qrcode-{gf}-{e}" for gf in ("table", "bitwise") for e in "LMQH"]
# The (variant, arch) configurations of each task's `make bench`, as (the variant's name up to its
# first '+', arch): T1 one build, T2 and T3 both builds and the second divider latency, T4 and T5
# three variants and both builds. A variant's options after '+' (a student's tick divisor or wait
# states, EX-08) do not change which configuration it is.
_Z = ("rv32i_zicsr", "rv32im_zicsr")
CONFIGS = {
    "T1": {("single-cycle", "rv32i")},
    "T2": {("div34", "rv32i"), ("div34", "rv32im"), ("div66", "rv32im")},
    "T3": {("div34", "rv32i_zicsr"), ("div34", "rv32im_zicsr"), ("div66", "rv32im_zicsr")},
    "T4": {(v, a) for v in ("Stall", "Forward", "EarlyBranch") for a in _Z},
    "T5": {(v, a) for v in ("Stall", "Forward", "EarlyBranch") for a in _Z},
}
EVENTS = {1: "div", 4: "load-use", 5: "flush", 6: "I-wait", 7: "D-wait", 8: "other"}


class ReportError(Exception):
    pass


def read_task(path, task):
    try:
        with open(path, encoding="utf-8", newline="") as f:
            rows = list(csv.reader(f))
    except OSError as e:
        raise ReportError(f"{path}: {e.strerror} (run 'make -C <task> bench' or 'make bench-all')") from e
    if not rows:
        raise ReportError(f"{path}: empty")
    header, body = rows[0], rows[1:]
    if not body:
        raise ReportError(f"{path}: no rows")
    if header not in (BASE, BASE + HPM):
        raise ReportError(f"{path}: unexpected columns {header}")
    seen, configs, out = set(), [], []
    for n, row in enumerate(body, 2):
        if len(row) != len(header):
            raise ReportError(f"{path}:{n}: {len(row)} fields, not {len(header)}")
        r = dict(zip(header, row))
        if r["task"] != task:
            raise ReportError(f"{path}:{n}: task {r['task']}, not {task}")
        if r["benchmark"] not in WORKLOADS:
            raise ReportError(f"{path}:{n}: unknown benchmark {r['benchmark']}")
        for k in ("cycles", "instret", "run_cycles", "run_instret") + tuple(h for h in HPM if h in r):
            if not r[k].isdigit():
                raise ReportError(f"{path}:{n}: {k} is '{r[k]}', not a count")
        key = (r["variant"], r["arch"], r["benchmark"])
        if key in seen:
            raise ReportError(f"{path}:{n}: {' '.join(key)} twice")
        seen.add(key)
        if (r["variant"], r["arch"]) not in configs:
            configs.append((r["variant"], r["arch"]))
        out.append(r)
    got = [(v.split("+")[0], a) for v, a in configs]
    if len(set(got)) != len(got) or set(got) != CONFIGS[task]:
        raise ReportError(f"{path}: the (variant, arch) configurations {sorted(got)} are not those of "
                          f"'make bench' in {task}: {sorted(CONFIGS[task])}")
    for variant, arch in configs:
        missing = [w for w in WORKLOADS if (variant, arch, w) not in seen]
        if missing:
            raise ReportError(f"{path}: {variant} {arch} has no row for {', '.join(missing)}")
    return out


def to_csv(rows):
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(BASE + HPM)
    for r in rows:
        w.writerow([r.get(k, "") for k in BASE + HPM])
    return buf.getvalue()


def to_md(rows, tasks):
    lines = ["<!-- Generated by scripts/bench-report.py from build/bench/t<n>.csv (`make bench`). -->",
             "# Benchmark report (BEN-03)", "",
             "One row per task, variant, build and workload. `cycles` and `instret` are the program's own",
             "counts between its benchmark markers; the partition events (from T3 on, docs/hpm-events.md) are",
             "those of the counters' region, where `hpm_cycles - hpm_instret` is their sum exactly.", ""]
    counts = {t: sum(r["task"] == t for r in rows) for t in tasks}
    lines += ["| task | rows |", "|---|---:|"] + [f"| {t} | {counts[t]} |" for t in tasks]
    lines += [f"| all | {len(rows)} |", ""]
    for t in tasks:
        part = [r for r in rows if r["task"] == t]
        hpm = "hpm1" in part[0] and part[0]["hpm1"] != ""
        head = ["variant", "arch", "benchmark", "cycles", "instret", "CPI", "score"]
        if hpm:
            head += [f"{EVENTS[i]} (hpm{i})" for i in sorted(EVENTS)]
        lines += [f"## {t}", "", "| " + " | ".join(head) + " |",
                  "|" + "|".join("---" if i < 3 else "---:" for i in range(len(head))) + "|"]
        for r in part:
            score = f"{r['score']} {r['score_unit']}" if r["score"] not in ("", "-") else "-"
            cells = [r["variant"], r["arch"], r["benchmark"], r["cycles"], r["instret"], r["cpi"], score]
            if hpm:
                cells += [r[f"hpm{i}"] for i in sorted(EVENTS)]
            lines.append("| " + " | ".join(cells) + " |")
        lines.append("")
    return "\n".join(lines)


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--bench", required=True, help="the directory of t<n>.csv")
    ap.add_argument("--out", required=True, help="the report's path without .csv/.md")
    ap.add_argument("--tasks", default=",".join(TASKS))
    a = ap.parse_args(argv)
    tasks = [t for t in a.tasks.split(",") if t]
    if not tasks or any(t not in TASKS for t in tasks):
        ap.error(f"--tasks takes some of {','.join(TASKS)}")
    try:
        rows = [r for t in tasks for r in read_task(os.path.join(a.bench, f"t{t[1]}.csv"), t)]
    except ReportError as e:
        print(f"bench-report: {e}", file=sys.stderr)
        return 1
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    for ext, text in ((".csv", to_csv(rows)), (".md", to_md(rows, tasks))):
        with open(a.out + ext + ".new", "w", encoding="utf-8", newline="") as f:
            f.write(text)
        os.replace(a.out + ext + ".new", a.out + ext)
    per = ", ".join(f"{t} {sum(r['task'] == t for r in rows)}" for t in tasks)
    print(f"bench-report: wrote {a.out}.csv and {a.out}.md ({len(rows)} rows: {per})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
