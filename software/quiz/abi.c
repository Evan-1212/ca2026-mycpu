// quiz_abi_call (runtime/include/quiz.h): call a routine of a quiz program with
// known values in the registers that it must give back, and report the ones it
// changed. It is the harness's: the quiz programs take it from here.
//
//   void quiz_abi_call(const void *fn, uint32_t x, uint32_t y,
//                      struct quiz_abi_result *out);
//   a0 = fn, a1 = x, a2 = y, a3 = out; the routine gets x in a0 and y in a1.

__asm__(
    "    .text\n"
    "    .globl quiz_abi_call\n"
    "    .type  quiz_abi_call, @function\n"
    "quiz_abi_call:\n"
    "    addi    sp, sp, -64\n"
    "    sw      ra, 60(sp)\n"
    "    sw      s0, 0(sp)\n"
    "    sw      s1, 4(sp)\n"
    "    sw      s2, 8(sp)\n"
    "    sw      s3, 12(sp)\n"
    "    sw      s4, 16(sp)\n"
    "    sw      s5, 20(sp)\n"
    "    sw      s6, 24(sp)\n"
    "    sw      s7, 28(sp)\n"
    "    sw      s8, 32(sp)\n"
    "    sw      s9, 36(sp)\n"
    "    sw      s10, 40(sp)\n"
    "    sw      s11, 44(sp)\n"
    "    sw      a3, 48(sp)\n"
    "    sw      sp, 52(sp)\n"
    "    mv      t0, a0\n"
    "    mv      a0, a1\n"
    "    mv      a1, a2\n"
    // canaries: s<k> = 0xC0DE0000 + 0x101 * k, so no two are equal
    "    lui     t1, 0xC0DE0\n"
    "    addi    s0, t1, 0x0\n"
    "    addi    s1, t1, 0x101\n"
    "    addi    s2, t1, 0x202\n"
    "    addi    s3, t1, 0x303\n"
    "    addi    s4, t1, 0x404\n"
    "    addi    s5, t1, 0x505\n"
    "    addi    s6, t1, 0x606\n"
    "    addi    s7, t1, 0x707\n"
    "    lui     t1, 0xC0DE1\n"
    "    addi    s8, t1, 0x0\n"
    "    addi    s9, t1, 0x101\n"
    "    addi    s10, t1, 0x202\n"
    "    addi    s11, t1, 0x303\n"
    "    jalr    ra, 0(t0)\n"
    // results first: t0/t1 are free again
    "    lw      t0, 48(sp)\n"
    "    sw      a0, 0(t0)\n"
    "    sw      a1, 4(t0)\n"
    "    li      t2, 0\n"
    "    lui     t1, 0xC0DE0\n"
    "    addi    t3, t1, 0x0\n"
    "    beq     s0, t3, 1f\n"
    "    ori     t2, t2, 1\n"
    "1:  addi    t3, t1, 0x101\n"
    "    beq     s1, t3, 1f\n"
    "    ori     t2, t2, 2\n"
    "1:  addi    t3, t1, 0x202\n"
    "    beq     s2, t3, 1f\n"
    "    ori     t2, t2, 4\n"
    "1:  addi    t3, t1, 0x303\n"
    "    beq     s3, t3, 1f\n"
    "    ori     t2, t2, 8\n"
    "1:  addi    t3, t1, 0x404\n"
    "    beq     s4, t3, 1f\n"
    "    ori     t2, t2, 16\n"
    "1:  addi    t3, t1, 0x505\n"
    "    beq     s5, t3, 1f\n"
    "    ori     t2, t2, 32\n"
    "1:  addi    t3, t1, 0x606\n"
    "    beq     s6, t3, 1f\n"
    "    ori     t2, t2, 64\n"
    "1:  addi    t3, t1, 0x707\n"
    "    beq     s7, t3, 1f\n"
    "    ori     t2, t2, 128\n"
    "1:  lui     t1, 0xC0DE1\n"
    "    addi    t3, t1, 0x0\n"
    "    beq     s8, t3, 1f\n"
    "    ori     t2, t2, 256\n"
    "1:  addi    t3, t1, 0x101\n"
    "    beq     s9, t3, 1f\n"
    "    ori     t2, t2, 512\n"
    "1:  addi    t3, t1, 0x202\n"
    "    beq     s10, t3, 1f\n"
    "    ori     t2, t2, 1024\n"
    "1:  addi    t3, t1, 0x303\n"
    "    beq     s11, t3, 1f\n"
    "    li      t4, 2048\n"
    "    or      t2, t2, t4\n"

    // sp: the value stored at 52(sp) at entry is the entry sp - 64 (= sp now if
    // kept)
    "1:  lw      t3, 52(sp)\n"
    "    beq     t3, sp, 1f\n"
    "    li      t4, 4096\n"
    "    or      t2, t2, t4\n"
    "1:  sw      t2, 8(t0)\n"
    "    lw      s0, 0(sp)\n"
    "    lw      s1, 4(sp)\n"
    "    lw      s2, 8(sp)\n"
    "    lw      s3, 12(sp)\n"
    "    lw      s4, 16(sp)\n"
    "    lw      s5, 20(sp)\n"
    "    lw      s6, 24(sp)\n"
    "    lw      s7, 28(sp)\n"
    "    lw      s8, 32(sp)\n"
    "    lw      s9, 36(sp)\n"
    "    lw      s10, 40(sp)\n"
    "    lw      s11, 44(sp)\n"
    "    lw      ra, 60(sp)\n"
    "    addi    sp, sp, 64\n"
    "    ret\n"
    "    .size  quiz_abi_call, .-quiz_abi_call\n");
